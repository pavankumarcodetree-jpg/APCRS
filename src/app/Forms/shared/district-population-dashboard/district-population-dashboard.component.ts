  private normalizeDistrictName(value: any): string {
    if (!value && value !== 0) {
      return '';
    }

    if (typeof value === 'string') {
      return value.trim();
    }

    if (typeof value === 'object') {
      return this.normalizeDistrictName(
        value.DISTRICT_NAME || value.districtName || value.district || value.name
      );
    }

    return value.toString().trim();
  }

  private resolveDistrictName(rawDistrict: any): string {
    if (!rawDistrict && rawDistrict !== 0) {
      return '';
    }

    if (typeof rawDistrict === 'string' && rawDistrict.trim()) {
      const decryptedDistrict = this.encDec.decrypt(rawDistrict);
      const candidate = decryptedDistrict && decryptedDistrict !== 'invalid' ? decryptedDistrict : rawDistrict;
      return this.normalizeDistrictName(candidate);
    }

    return this.normalizeDistrictName(rawDistrict);
  }

  private normalizeDistrictKey(value: string): string {
    const normalized = (value || '').toLowerCase().replace(/[^a-z0-9]+/g, '');

    const withSpellingFixes = normalized
      .replace(/sitha/g, 'seetha')
      .replace(/seeta/g, 'seetha')
      .replace(/sithar/g, 'seethar')
      .replace(/seetar/g, 'seethar')
      .replace(/godavai/g, 'godavari');

    const canonicalAliases: Record<string, string> = {
      alluriseetaramaraju: 'alluriseetharamaraju',
      allurisitharamaraju: 'alluriseetharamaraju',
      alluriseetharamaraju: 'alluriseetharamaraju',
      eastgodavai: 'eastgodavari',
      eastgodavari: 'eastgodavari'
    };

    return canonicalAliases[withSpellingFixes] || withSpellingFixes;
  }

